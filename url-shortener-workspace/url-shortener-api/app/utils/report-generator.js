const PDFDocument = require("pdfkit");
const { Parser } = require("json2csv");

class ReportGenerator {
  /**
   * Enterprise-Grade PDF Table & Document Generator
   */
  static buildStyledPdfStream({
    title,
    userInfo = {},
    headers = [],
    rows = [],
    primaryColor = "#2563EB"
  }) {
    const doc = new PDFDocument({ margin: 30, size: "A4" });

    // --- 1. BRAND HEADER BANNER ---
    doc
      .rect(0, 0, doc.page.width, 60)
      .fill(primaryColor);

    doc
      .fillColor("#FFFFFF")
      .fontSize(20)
      .text(title.toUpperCase(), 30, 20, { align: "left" });

    // --- 2. USER METADATA BOX ---
    doc
      .fillColor("#333333")
      .fontSize(10)
      .text(`Generated For: ${userInfo.name || "N/A"} (${userInfo.email || "N/A"})`, 30, 75)
      .text(`Generated On: ${new Date().toLocaleString()}`, 30, 90);

    if (userInfo.dateRange) {
      doc.text(`Filter Range: ${userInfo.dateRange}`, 30, 105);
    }

    let startY = userInfo.dateRange ? 130 : 115;

    // --- 3. EMPTY STATE CHECK ---
    if (rows.length === 0) {
      doc
        .fontSize(12)
        .fillColor("#666666")
        .text("No records found matching the specified criteria.", 30, startY + 20);
      doc.end();
      return doc;
    }

    // --- 4. TABLE DRAWING CONFIGURATION ---
    const tableTop = startY + 10;
    const pageMargin = 30;
    const usableWidth = doc.page.width - pageMargin * 2;
    
    const colWidths = headers.map((h) => (h.widthPercent / 100) * usableWidth);

    // Header Bar - Increased height from 22pt to 26pt to prevent text clipping
    const headerHeight = 26;
    doc
      .rect(pageMargin, tableTop, usableWidth, headerHeight)
      .fill("#F3F4F6");

    let currentX = pageMargin;
    doc.fillColor("#111827").fontSize(8.5).font("Helvetica-Bold");

    headers.forEach((header, i) => {
      doc.text(header.label, currentX + 3, tableTop + 8, {
        width: colWidths[i] - 6,
        align: header.align || "left",
        lineBreak: false // Prevents label wrapping onto a 2nd line
      });
      currentX += colWidths[i];
    });

    // Draw Table Rows
    let currentY = tableTop + headerHeight;
    const rowHeight = 22; // Slightly higher row height for cleaner padding
    doc.font("Helvetica").fontSize(8);

    rows.forEach((row, rowIndex) => {
      if (currentY + rowHeight > doc.page.height - 50) {
        doc.addPage();
        currentY = 40;
      }

      // Alternating Zebra Row Background
      if (rowIndex % 2 === 0) {
        doc.rect(pageMargin, currentY, usableWidth, rowHeight).fill("#F9FAFB");
      }

      let rowX = pageMargin;
      doc.fillColor("#374151");

      headers.forEach((header, colIndex) => {
        const cellValue = String(row[header.key] ?? "-");
        doc.text(cellValue, rowX + 3, currentY + 7, {
          width: colWidths[colIndex] - 6,
          align: header.align || "left",
          ellipsis: true
        });
        rowX += colWidths[colIndex];
      });

      // Bottom Row Border Line
      doc
        .moveTo(pageMargin, currentY + rowHeight)
        .lineTo(pageMargin + usableWidth, currentY + rowHeight)
        .strokeColor("#E5E7EB")
        .lineWidth(0.5)
        .stroke();

      currentY += rowHeight;
    });

    // --- 5. DYNAMIC FOOTER & PAGE NUMBERS ---
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      doc
        .fontSize(8)
        .fillColor("#9CA3AF")
        .text(
          `Page ${i + 1} of ${range.count}  |  Confidential - Generated by URL Shortener Service`,
          pageMargin,
          doc.page.height - 30,
          { align: "center", width: usableWidth }
        );
    }

    doc.end();
    return doc;
  }

  static buildCsvString({ fields, data }) {
    const json2csvParser = new Parser({ fields });
    return json2csvParser.parse(data);
  }
}

module.exports = ReportGenerator;